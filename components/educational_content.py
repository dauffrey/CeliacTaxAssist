import streamlit as st

def render_educational_content():
    st.subheader("Understanding Celiac Tax Credits")
    
    st.markdown("""
    ### CRA Guidelines for Celiac Disease Tax Credits
    
    The incremental costs of purchasing gluten-free (GF) products can be claimed as a medical expense on your tax return. Here's what you need to know:
    
    1. **Eligible Products**
        - Gluten-free bread
        - Gluten-free muffins
        - Gluten-free cereals
        - Other gluten-free products
        
    2. **Calculation Method**
        - Calculate the difference between GF products and regular products
        - Keep all receipts for documentation
        - Track purchases throughout the year
        
    3. **Documentation Required**
        - Medical documentation of Celiac disease
        - Receipts for GF products
        - Receipts or price comparisons for regular products
        
    4. **Filing Process**
        - Use this app to track your expenses
        - Generate a yearly report
        - Include with your tax return
    """)
